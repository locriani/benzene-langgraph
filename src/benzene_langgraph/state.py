"""LangGraph state schema and reducers for the Kekulé Benzene (C6H6) workflow."""

from __future__ import annotations

import operator
from typing import Annotated, Literal, TypedDict


def merge_dicts[K, V](left: dict[K, V] | None, right: dict[K, V] | None) -> dict[K, V]:
    """Merge parallel atomic orbital updates from concurrent Pregel supersteps."""
    merged: dict[K, V] = dict(left or {})
    if right:
        merged.update(right)
    return merged


def merge_synthesis_blocks(left: str | None, right: str | None) -> str:
    """Combine parallel terminal Carbon orbital synthesis sections in ring order."""
    blocks = [b for b in (left, right) if b]
    if not blocks:
        return ""
    lines: list[str] = []
    for block in blocks:
        for line in block.splitlines():
            if line and line not in lines:
                lines.append(line)
    header = [ln for ln in lines if ln.startswith("### ")]
    items = sorted(
        (ln for ln in lines if ln.startswith("- **C")),
        key=lambda ln: ln[:7],
    )
    return "\n\n".join([*header, *items])


class BondTraversal(TypedDict):
    """Audit record of an electron/message handoff across a covalent bond."""

    source: str
    target: str
    bond_type: Literal["sigma_CH", "sigma_CC", "double_sigma", "double_pi"]
    round: int


class BenzeneState(TypedDict, total=False):
    """Molecular state shared across the 6 Hydrogen and 6 Carbon nodes."""

    # Input query entering the benzene molecule
    prompt: str

    # 1s orbital outputs generated by H1..H6 (gemini-4-hydrogen)
    hydrogen_orbitals: Annotated[dict[str, str], merge_dicts]

    # Directional sigma-bond channels ("H1->C1", "C2->C3", "C1->C2", ...)
    sigma_channels: Annotated[dict[str, str], merge_dicts]

    # Conjugated pi-bond channels strictly restricted to C=C double bonds ("C1=>C2", "C2=>C1", ...)
    pi_channels: Annotated[dict[str, str], merge_dicts]

    # Current sp2 + 2pz reasoning states of C1..C6 (gemini-4-carbon)
    carbon_orbitals: Annotated[dict[str, str], merge_dicts]

    # Stabilized C=C double-bond dimers ("C1=C2", "C3=C4", "C5=C6" or Isomer B equivalents)
    pi_dimers: Annotated[dict[str, str], merge_dicts]

    # Per-carbon conjugation round index
    carbon_rounds: Annotated[dict[str, int], merge_dicts]

    # Ordered log of every covalent bond traversal during execution
    bond_traversals: Annotated[list[BondTraversal], operator.add]

    # Superstep execution trace
    execution_trace: Annotated[list[str], operator.add]

    # Final stabilized orbitals from the terminal conjugation superstep, keyed by atom
    terminal_orbitals: Annotated[dict[str, str], merge_dicts]

    # Converged Kekulé aromatic synthesis
    aromatic_synthesis: Annotated[str, merge_synthesis_blocks]

